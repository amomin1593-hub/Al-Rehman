-- Categories, collections, finishes ------------------------------------
create table if not exists public.categories (
  slug        text primary key,
  name        text not null,
  tagline     text default '',
  description text default '',
  sort        int  default 0
);

create table if not exists public.collections (
  slug text primary key,
  name text not null,
  line text default '',
  sort int  default 0
);

create table if not exists public.finishes (
  slug text primary key,
  name text not null,
  hex  text default '#cccccc',
  sort int  default 0
);

-- Products ------------------------------------------------------------
create table if not exists public.products (
  id          bigint generated by default as identity primary key,
  slug        text unique not null,
  sku         text,
  name        text not null,
  category    text references public.categories(slug) on update cascade,
  collection  text references public.collections(slug) on update cascade,
  price       integer not null default 0,
  compare_at  integer,
  finishes    jsonb   not null default '[]'::jsonb,
  specs       jsonb   not null default '{}'::jsonb,
  art         text    default 'faucet-basin',
  tone        text    default '#ece8e1',
  badge       text,
  rating      numeric(2,1) default 5,
  reviews     integer default 0,
  stock       integer not null default 0 check (stock >= 0),
  featured    boolean not null default false,
  description text    default '',
  image_url   text,
  created_at  timestamptz default now(),
  updated_at  timestamptz default now()
);
create index if not exists products_category_idx on public.products (category);
-- photo gallery (added later; safe to re-run)
alter table public.products add column if not exists images jsonb not null default '[]'::jsonb;

create or replace function public.touch_updated_at() returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end $$;
drop trigger if exists products_touch on public.products;
create trigger products_touch before update on public.products
  for each row execute function public.touch_updated_at();

-- Home page content and other site settings (JSON) --------------------
create table if not exists public.site_content (
  key        text primary key,
  value      jsonb not null,
  updated_at timestamptz default now()
);

-- Orders --------------------------------------------------------------
create table if not exists public.orders (
  id         text primary key,
  created_at timestamptz not null default now(),
  status     text not null default 'Processing',
  payment    text,
  customer   jsonb not null,
  items      jsonb not null,
  subtotal   integer not null,
  shipping   integer not null default 0,
  total      integer not null
);
create index if not exists orders_created_idx on public.orders (created_at desc);

-- Keeps the product id counter ahead of imported ids
create or replace function public.sync_product_id_seq() returns void
language sql security definer set search_path = public as $$
  select setval(pg_get_serial_sequence('public.products', 'id'),
                greatest(coalesce((select max(id) from public.products), 0), 1));
$$;

-- Security ------------------------------------------------------------
-- The website talks to the database only from the server, using the secret key.
-- Row Level Security is ON with no public policies, so the public keys can't read or change anything.
alter table public.categories   enable row level security;
alter table public.collections  enable row level security;
alter table public.finishes     enable row level security;
alter table public.products     enable row level security;
alter table public.site_content enable row level security;
alter table public.orders       enable row level security;

grant usage on schema public to service_role;
grant all on all tables    in schema public to service_role;
grant all on all sequences in schema public to service_role;
grant execute on function public.sync_product_id_seq() to service_role;
revoke execute on function public.sync_product_id_seq() from public, anon, authenticated;

-- Storage bucket for uploaded photos (public read) --------------------
insert into storage.buckets (id, name, public)
values ('media', 'media', true)
on conflict (id) do update set public = true;
